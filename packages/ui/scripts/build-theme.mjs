// Builds dist/themes/neutral.css: the palette and scale variables from
// themes/neutral.tokens.json, one block per colour scheme, followed by the
// mapping onto Utrecht component tokens (themes/neutral.mapping.css).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const root = new URL('../', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('themes/neutral.tokens.json', root), 'utf8'));
const mapping = readFileSync(new URL('themes/neutral.mapping.css', root), 'utf8');

// Every Utrecht token the mapping sets must be one the Utrecht CSS reads; a
// misspelt or removed token would otherwise do nothing, silently.
const utrecht = readFileSync(createRequire(import.meta.url).resolve('@utrecht/component-library-css/dist/index.css'), 'utf8');
const read = new Set([...utrecht.matchAll(/var\((--utrecht-[a-z0-9-]+)/g)].map((m) => m[1]));
const unread = [...new Set([...mapping.matchAll(/^\s*(--utrecht-[a-z0-9-]+):/gm)].map((m) => m[1]))].filter((name) => !read.has(name));
if (unread.length > 0) {
    console.error(`The mapping sets Utrecht tokens that Utrecht CSS never reads: ${unread.join(', ')}`);
    process.exit(1);
}

const block = (selector, entries) =>
    `${selector} {\n${entries.map(([name, value]) => `  --mc-neutral-${name}: ${value};`).join('\n')}\n}\n`;

const scale = [...Object.entries(tokens.dimension), ...Object.entries(tokens.font)];

// Every variable the mapping uses must be defined, in every colour scheme.
const defined = new Set(scale.map(([name]) => name));
for (const [scheme, colours] of Object.entries(tokens.color)) {
    const names = new Set([...defined, ...Object.keys(colours)]);
    const missing = [...mapping.matchAll(/var\(--mc-neutral-([a-z0-9-]+)\)/g)].map((m) => m[1]).filter((name) => !names.has(name));
    if (missing.length > 0) {
        console.error(`${scheme}: the mapping uses undefined variables: ${[...new Set(missing)].join(', ')}`);
        process.exit(1);
    }
}

const css = [
    '/* Generated by scripts/build-theme.mjs from themes/neutral.tokens.json. Do not edit. */\n',
    block(":root,\n.mc-neutral-theme,\n[data-color-scheme='light']", Object.entries(tokens.color.light)),
    block("[data-color-scheme='dark']", Object.entries(tokens.color.dark)),
    block("[data-color-scheme='contrast']", Object.entries(tokens.color.contrast)),
    block(':root,\n.mc-neutral-theme', scale),
    mapping,
].join('\n');

mkdirSync(new URL('dist/themes/', root), { recursive: true });
writeFileSync(new URL('dist/themes/neutral.css', root), css);
console.log('dist/themes/neutral.css written');
